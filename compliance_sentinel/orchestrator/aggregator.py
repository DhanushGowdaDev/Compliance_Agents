"""
aggregator.py — Orchestrator Tool (v2)
Merges all specialist ratings + benchmarks + redlines + compromises into:
  - scorecard.json        (flat list, backward compat)
  - buyer_view.json       (2D risk map sorted by impact)
  - vendor_view.json      (Red/Amber only, sorted by likelihood)
  - scorecard.html        (Red/Amber/Green colour-coded table)
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

# ---------------------------------------------------------------------------
# 2D Risk Score Lookup  rule_id → (likelihood 1-10, impact 1-10)
# Amber = base * 0.70, Green = (2, 2), N/A = (1, 1)
# ---------------------------------------------------------------------------
_RISK: dict[str, dict[str, tuple[int, int]]] = {
    "legal_agent": {
        "R1": (8, 9), "R2": (7, 9), "R3": (6, 6),
        "R4": (5, 7), "R5": (4, 6), "R6": (5, 5),
    },
    "data_privacy_agent": {
        "R1": (7, 10), "R2": (6, 9), "R3": (5, 6),
        "R4": (6, 8),  "R5": (7, 8), "R6": (5, 6), "R7": (6, 7),
    },
    "commercial_agent": {
        "R1": (7, 5), "R2": (6, 4), "R3": (8, 8),
        "R4": (7, 8), "R5": (6, 5), "R6": (5, 9),
    },
}
_DEFAULT_SCORE = (4, 4)

# Vendor-perspective: which rules represent concessions from vendor
_VENDOR_RULES = {
    "legal_agent":         {"R1", "R2", "R5", "R6"},
    "data_privacy_agent":  {"R1", "R2", "R4", "R5", "R6", "R7"},
    "commercial_agent":    {"R3", "R4", "R6"},
}


def _risk_coords(agent: str, rule_id: str, rating: str) -> tuple[int, int]:
    base = _RISK.get(agent, {}).get(rule_id, _DEFAULT_SCORE)
    if rating == "Green" or rule_id == "N/A":
        return (2, 2)
    if rating == "Amber":
        return (max(1, round(base[0] * 0.70)), max(1, round(base[1] * 0.70)))
    return base  # Red


