def _html_row(e: dict) -> str:
    rating = e.get("rating", "Green")
    bench  = e.get("benchmark_verdict", "")
    bench_cls = {"aggressive": "bench-agg", "standard": "bench-std",
                 "lenient": "bench-len"}.get(bench, "")
    redline = e.get("suggested_redline", "")
    redline_html = f"<br><pre>✏ {redline[:180]}</pre>" if redline and "unavailable" not in redline else ""
    bg     = _BG.get(rating, "transparent")
    color  = _COLORS.get(rating, "#64748b")
    emoji  = _EMOJI.get(rating, "")
    cid    = e.get("clause_id", "")
    agent  = e.get("agent_source", "")
    rule   = e.get("rule_id", "N/A")
    reason = e.get("reason", "")
    bench_tag = f'<span class="bench {bench_cls}">{bench}</span>' if bench else "—"
    return (
        f'<tr style="background:{bg}">'
        f'<td><strong>{cid}</strong></td>'
        f'<td><span class="agent">{agent}</span></td>'
        f'<td><span class="badge" style="background:{color}">{emoji} {rating}</span></td>'
        f'<td><span class="rule">{rule}</span></td>'
        f'<td>{bench_tag}</td>'
        f'<td>{reason}{redline_html}</td>'
        f'</tr>'
    )


# ---------------------------------------------------------------------------
# Main aggregate function
# ---------------------------------------------------------------------------

def aggregate(
    responses: list[dict[str, Any]],
    benchmarks: dict[str, dict] | None = None,
    redlines: dict[str, dict] | None = None,
    compromises: dict[str, list] | None = None,
    contract_id: str = "default",
    output_dir: str = ".",
    output_html: str | None = None,
    output_json: str | None = None,
) -> dict[str, Any]:
    """
    Merge all data into risk map entries + buyer/vendor views.

    Args:
        responses:   List of {clause_id, agent, rating, rule_id, reason} from specialist agents.
        benchmarks:  Dict clause_id → benchmark_clause() result.
        redlines:    Dict clause_id → generate_redline() result.
        compromises: Dict clause_id → list of propose_compromise() results.
        contract_id: Identifier for this contract run.
        output_dir:  Directory to write output files.
    """
    benchmarks  = benchmarks  or {}
    redlines    = redlines    or {}
    compromises = compromises or {}

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    # Validate + normalise responses
    clean: list[dict] = []
    for r in responses:
        if not isinstance(r, dict):
            continue
        rating  = r.get("rating", "Green")
        if rating not in ("Red", "Amber", "Green"):
            rating = "Green"
        agent   = str(r.get("agent", "unknown"))
        rule_id = str(r.get("rule_id", "N/A"))
        cid     = str(r.get("clause_id", "?"))

        x, y = _risk_coords(agent, rule_id, rating)
        bench = benchmarks.get(cid, {})
        redl  = redlines.get(cid, {})

        entry: dict[str, Any] = {
            "clause_id":         cid,
            "agent_source":      agent,
            "rating":            rating,
            "rule_id":           rule_id,
            "reason":            str(r.get("reason", "")),
            "x_likelihood":      x,
            "y_impact":          y,
            "benchmark_verdict": bench.get("benchmark_verdict", ""),
            "comparison_note":   bench.get("comparison_note", ""),
            "area":              bench.get("area", ""),
            "suggested_redline": redl.get("suggested_redline", ""),
            "rule_id_addressed": redl.get("rule_id_addressed", ""),
            "compromise_options": compromises.get(cid, []),
        }
        clean.append(entry)

    # Sort: clause numerically then agent
    def _key(e: dict) -> tuple:
        parts = e["clause_id"].replace("_", ".").split(".")
        num = []
        for p in parts:
            try: num.append(int(p))
            except ValueError: num.append(p)
        return (num, e["agent_source"])

    clean.sort(key=_key)

    red   = sum(1 for e in clean if e["rating"] == "Red")
    amber = sum(1 for e in clean if e["rating"] == "Amber")
    green = sum(1 for e in clean if e["rating"] == "Green")

    # --- scorecard.json (flat, backward compat)
    sc_path = out / (output_json or "scorecard.json")
    sc_path.write_text(json.dumps(clean, indent=2), encoding="utf-8")

    # --- buyer_view.json: all entries, highest impact first
    buyer = sorted(clean, key=lambda e: (-e["y_impact"], -e["x_likelihood"]))
    (out / "buyer_view.json").write_text(
        json.dumps({
            "contract_id": contract_id,
            "perspective": "buyer",
            "description": "Sorted by compliance impact — address highest-impact risks first.",
            "risk_map": buyer,
            "summary": {"total": len(clean), "red": red, "amber": amber, "green": green},
        }, indent=2),
        encoding="utf-8",
    )

    # --- vendor_view.json: Red+Amber only, sorted by likelihood (deal blockers first)
    vendor_entries = [e for e in clean if e["rating"] in ("Red", "Amber")]
    vendor = sorted(
        vendor_entries,
        key=lambda e: (
            -e["x_likelihood"],
            0 if _VENDOR_RULES.get(e["agent_source"], set()) & {e["rule_id"]} else 1,
        ),
    )
    (out / "vendor_view.json").write_text(
        json.dumps({
            "contract_id": contract_id,
            "perspective": "vendor",
            "description": "Clauses requiring vendor concession, sorted by deal-blocking likelihood.",
            "risk_map": vendor,
            "summary": {"total": len(vendor_entries), "red": red, "amber": amber},
        }, indent=2),
        encoding="utf-8",
    )

    # --- scorecard.html
    rows = "\n".join(_html_row(e) for e in clean)
    html = _HTML.format(total=len(clean), red=red, amber=amber, green=green, rows=rows)
    html_path = out / (output_html or "scorecard.html")
    html_path.write_text(html, encoding="utf-8")

    return {
        "scorecard":   clean,
        "summary":     {"total": len(clean), "red": red, "amber": amber, "green": green},
        "html_path":   str(html_path.resolve()),
        "json_path":   str(sc_path.resolve()),
        "buyer_path":  str((out / "buyer_view.json").resolve()),
        "vendor_path": str((out / "vendor_view.json").resolve()),
        "contract_id": contract_id,
    }
